const QUICK = [['c5', 'L3'], ['c4', 'L3'], ['c1', 'L2'], ['u1', 'L1'], ['u3', 'L1s'], ['a1', 'ADM']];
const ZAPS = [['zCrisis', '新危机'], ['zTime', '时间 +4 小时'], ['zWave', '又有 6 人完成'], ['zBook', '学生提交 2 个预约']];
function boot() {
  $('#roleSel').innerHTML = '<option value="">登录页（未登录）</option>' + QUICK.map(([u, r]) => `<option value="${u}|${r}">${ST(u).name} · ${RN[r]}</option>`).join('');
  $('#zaps').innerHTML = ZAPS.map(([a, n]) => `<button class="zap" data-act="${a}">⚡ ${n}</button>`).join('');
  $('#roleSel').onchange = e => { const v = e.target.value; if (!v) { if (S.uid) ACT.logout(); } else { if (S.uid) log('退出登录', null, { cat: '登录' }); const [u, r] = v.split('|'); enter(u, r, '演示快速登录'); } render(); };
  $('#jump').onchange = e => { go(e.target.value); render(); };
  $('#zapT').onchange = e => document.body.classList.toggle('demo-on', e.target.checked);
  $('#memoBtn').onclick = () => { S.memo = !S.memo; renderShell(); };
  $('#resetBtn').onclick = () => location.reload();
  render();
}
function renderShell() {
  $('#roleSel').value = S.uid ? `${S.uid}|${S.role}` : '';
  $('#jump').innerHTML = S.uid ? MENUS[S.role].filter(m => !m[3] || m[0] === S.page).map(([k, n]) => `<option value="${k}" ${S.page === k ? 'selected' : ''}>${n}</option>`).join('') : '<option>—</option>';
  $('#jump').disabled = !S.uid;
  const m = S.uid ? (MEMO[S.role] || {})[S.page] : MEMO.login;
  $('#memo').innerHTML = S.memo ? `<div class="memo"><h4>📝 ${S.uid ? `${RN[S.role]} · ${TITLES[S.page]}` : '登录'}</h4>${m ? `<ul>${m.map(x => `<li>${x}</li>`).join('')}</ul>` : '<p>这一页没有额外说明。</p>'}</div>` : '';
}
